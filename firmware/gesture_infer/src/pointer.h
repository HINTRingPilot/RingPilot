// 5방향 스위치 포인터. 반지는 스위치 상태와 클릭만 보내고, 커서는 앱(접근성 서비스)이 화면 위에 그린다.
// 그래서 커서를 평소에는 숨기고 쓸 때만 잠깐 보이게 할 수 있다(HID 마우스는 폰이 커서를 관리해 이걸 정할 수 없다).
// BLE 특성 b27a2004(notify): [순번 uint8][방향 상태 uint8: 1 위, 2 아래, 4 왼쪽, 8 오른쪽][클릭 수 uint8, 한 바퀴 돌면 0부터].
//  - 패킷은 변화가 아니라 "지금 상태"라서 하나를 놓쳐도 다음 패킷으로 바로잡힌다. 앱은 클릭 수가 바뀌면 그만큼 탭한다.
//  - 앱이 구독하면 지금 상태를 한 번 보낸다(앱은 이 클릭 수를 기준으로 삼는다). 상태나 클릭이 바뀌면 보내고, 방향을 누르고 있는 동안은 200 ms마다 다시 보낸다(앱이 뗌을 놓쳐도 멈출 수 있게).
//  - 보내기에 실패하면 다음 poll에서 다시 보낸다.
// 센터 짧게 누르기 = 클릭(controls가 부른다). 일시정지 중에도 동작한다(일시정지는 제스처 인식만 멈춘다).
// 방향 핀: 위 D6, 아래 D0, 왼쪽 D3, 오른쪽 D2. 시리얼이 연결돼 있으면 누를 때 핀과 방향을 찍는다.
#pragma once

#include <stdint.h>

void pointer_begin();            // 핀 설정과 BLE 특성 시작. ble_begin이 서비스 안에서 부른다(특성 순서 유지)
void pointer_poll(uint32_t nowMs);  // loop마다: 방향 스위치를 읽고, 바뀌었거나 보낼 때가 되면 상태를 보낸다
void pointer_click();            // 클릭 수를 하나 늘리고 다음 poll에서 보낸다
